function getLocale(): AdminLocale {
  if (typeof window === "undefined") return "ru";
  try {
    return localStorage.getItem(STORAGE_KEY) === "kg" ? "kg" : "ru";
  } catch {
    return "ru";
  }
}

function subscribe(listener: () => void) {
  const onStorage = (event: StorageEvent) => {
    if (event.key === STORAGE_KEY || event.key === null) {
      memoryLocale = null;
      listener();
    }
  };
  window.addEventListener(CHANGE_EVENT, listener);
  window.addEventListener("storage", onStorage);
  return () => {
    window.removeEventListener(CHANGE_EVENT, listener);
    window.removeEventListener("storage", onStorage);
  };
}

let memoryLocale: AdminLocale | null = null;
const snapshot = () => memoryLocale ?? getLocale();

export function setAdminLocale(locale: AdminLocale) {
  memoryLocale = locale;
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    // Keep the preference for this tab when storage is unavailable.
  }
  window.dispatchEvent(new Event(CHANGE_EVENT));
}

export function translateAdmin(text: string, locale: AdminLocale): string {
  if (locale === "ru" || !text) return text;
  if (Object.hasOwn(kg, text)) return kg[text];
  const progress = /^(Оптимизация|Загрузка): (\d+) из (\d+)$/.exec(text);
  if (progress) {
    const action = progress[1] === "Оптимизация" ? "Оптималдаштыруу" : "Жүктөө";
    return `${action}: ${progress[2]} / ${progress[3]}`;
  }
  const prefixTranslations: Record<string, string> = {
    "Оригинал сохранён: ": "Оригиналы сакталды: ",
    "Не удалось подготовить изображение: ": "Сүрөттү даярдоо мүмкүн болгон жок: ",
    "Не удалось загрузить изображение: ": "Сүрөттү жүктөө мүмкүн болгон жок: ",
  };
  for (const [prefix, translated] of Object.entries(prefixTranslations)) {
    if (text.startsWith(prefix)) return translated + text.slice(prefix.length);
  }
  // Translate only summary lines; article titles and file names remain verbatim.
  return text
    .replace(/^Удалено: (\d+)/, "Өчүрүлдү: $1")
    .replace(/\nНе удалось удалить: (\d+)/, "\nӨчүрүү мүмкүн болгон жок: $1");
}

export function useAdminI18n() {
  const locale = useSyncExternalStore(subscribe, snapshot, () => "ru" as AdminLocale);
  return { locale, t: (text: string) => translateAdmin(text, locale), setLocale: setAdminLocale };
}

export function formatAdminDate(value: string | null, locale: AdminLocale) {
  if (!value) return "-";
  const date = new Date(value);
  const time = new Intl.DateTimeFormat(locale === "kg" ? "ky-KG" : "ru-RU", {
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  }).format(date);
  return `${formatNewsDate(value, locale)}, ${time}`;
}
